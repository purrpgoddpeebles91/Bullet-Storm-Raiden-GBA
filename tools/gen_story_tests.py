#!/usr/bin/env python3
"""Writes tests/v03_story_{nn,nd,dn,dd}.txt: debug+STORY runs through World 1 on each route combo,
screenshotting every story scene (stage briefings, boss talk before/after, the ending scene and results)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def scene(L, name, lines=2, menu=False):
    # shot line 1, advance, shot line 2, then skip the rest with START
    L += ['wait 75', 'shot %s_a' % name]
    if lines > 1:
        L += ['press A', 'wait 75', 'shot %s_b' % name]
    L += ['press START', 'wait 10']

def boss(L, tag, main=False, sub=0):
    L += ['press SELECT', 'hold A 290']           # skip to WARNING, boss flies in -> pre-fight talk
    scene(L, tag + '_pre')
    L += ['hold A 60', 'shot %s_fight' % tag]
    n = 4 if main else 3                          # debug SELECT takes 1/3 HP (main boss: phase shields eat one)
    for i in range(n):
        L += ['press SELECT', 'wait 80']
    L += ['wait 70']                              # boss explodes (100) -> post talk at 140
    scene(L, tag + '_post')
    L += ['wait 250']                             # SUB-LEVEL CLEAR -> fork / ending

def make(combo):
    r1, r2 = combo[0], combo[1]
    L = ['# generated by tools/gen_story_tests.py - route %s (N = nightmare, D = dream)' % combo.upper(),
         'wait 60', 'hold L+R 5', 'hold L+R+SELECT 3', 'hold L+R+UP 3', 'wait 20',
         'press START', 'press A', 'wait 10', 'press DOWN', 'press A', 'wait 10',   # START RUN, NORMAL
         'press A', 'wait 10', 'press A', 'wait 5']                                  # Nightjet, slot 1
    scene(L, 'v03_story_%s_intro' % combo, 1)
    L += ['wait 50', 'shot v03_story_%s_stage11' % combo, 'hold A 210']
    boss(L, 'v03_story_%s_warden' % combo)
    # fork 1
    L += ['wait 20'] + (['press DOWN'] if r1 == 'd' else []) + ['wait 5', 'shot v03_story_%s_fork1' % combo, 'press A', 'wait 20',
          'press A', 'wait 10', 'press A', 'wait 10']        # node (gamble / merchant): yes, onward
    scene(L, 'v03_story_%s_pre12' % combo)
    L += ['wait 50', 'shot v03_story_%s_stage12' % combo, 'hold A 290']
    boss(L, 'v03_story_%s_boss12' % combo)
    L += ['wait 20'] + (['press DOWN'] if r2 == 'd' else []) + ['wait 5', 'shot v03_story_%s_fork2' % combo, 'press A', 'wait 20',
          'press DOWN', 'press DOWN', 'press DOWN', 'press A', 'wait 10']   # shop: leave
    scene(L, 'v03_story_%s_pre13' % combo)
    L += ['wait 50', 'shot v03_story_%s_stage13' % combo, 'hold A 290']
    boss(L, 'v03_story_%s_boss13' % combo, main=True, sub=2)
    L += ['wait 10']
    scene(L, 'v03_story_%s_ending' % combo, 2)
    L += ['wait 90', 'shot v03_story_%s_results' % combo, 'press START', 'wait 30',
          'press DOWN', 'press DOWN', 'press DOWN', 'press DOWN', 'press A', 'wait 20', 'shot v03_story_%s_memories' % combo]
    open(os.path.join(ROOT, 'tests', 'v03_story_%s.txt' % combo), 'w').write('\n'.join(L) + '\n')

for c in ('nn', 'nd', 'dn', 'dd'):
    make(c)
print('ok')
