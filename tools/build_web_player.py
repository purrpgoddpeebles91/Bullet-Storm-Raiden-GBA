#!/usr/bin/env python3
"""Regenerate the Bullet Storm Raiden web player from any ROM.

  python3 tools/build_web_player.py [ROM] [--skins] [--no-site] [--no-single]

Outputs (paths relative to the project root):
  web/bsr-player.js      gbajs (BSD-2) + open-source BIOS (base64) + ROM (base64) + BSRPlayer API
  web/bsr-app.js         shell art + video pipeline + player UI (web/src/bsr-shell.js, bsr-video.js, bsr-ui.js)
  site/                  static GitHub Pages folder: index.html, bsr-player.js, bsr-app.js, the .gba,
                         gbajs-LICENSE.txt, .nojekyll, downloads/ (skins, when built)
  dist/web/BulletStormRaiden_web_single.html   one self-contained HTML file (everything inlined)
  --skins also runs tools/build_skins.py first (needs chromium) so site/downloads gets fresh skins.

Default ROM: dist/BulletStormRaiden_v0.2.gba. Nothing in game/ is read or written.
"""
import argparse, base64, hashlib, html, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GBAJS = os.path.join(ROOT, 'web', 'gbajs')
SRC = os.path.join(ROOT, 'web', 'src')
GBAJS_FILES = ['util', 'core', 'arm', 'thumb', 'mmu', 'io', 'audio', 'video', 'video/proxy', 'video/software',
               'irq', 'keypad', 'sio', 'savedata', 'gpio', 'gba']


def rd(p, mode='r'):
    with open(p, mode) as f:
        return f.read()


def wr(p, data):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'wb' if isinstance(data, bytes) else 'w') as f:
        f.write(data)


def rom_info(rom, path):
    if len(rom) < 0xC0 or rom[0xB2] != 0x96:
        sys.exit('not a GBA ROM (header fixed byte 0xB2 != 0x96): %s' % path)
    title = rom[0xA0:0xAC].split(b'\0')[0].decode('ascii', 'replace').strip()
    code = rom[0xAC:0xB0].decode('ascii', 'replace')
    chk = (-(sum(rom[0xA0:0xBD]) + 0x19)) & 0xFF
    m = re.search(r'v(\d+(?:\.\d+)+)', os.path.basename(path))
    return {'title': title, 'code': code, 'bytes': len(rom), 'md5': hashlib.md5(rom).hexdigest(),
            'version': ('v' + m.group(1)) if m else '', 'header_ok': chk == rom[0xBD], 'file': os.path.basename(path)}


def build_bundle(rom, info):
    lic = rd(os.path.join(GBAJS, 'COPYING')).strip()
    head = ('/*\n gbajs by Jeffrey Pfau (endrift), BSD 2-clause license:\n' + lic +
            '\n\n Bullet Storm Raiden (c) 2026 Zachary Peebles. Original homebrew.\n'
            ' Built by tools/build_web_player.py from %s (%d bytes, md5 %s).\n*/\n') % (info['file'], info['bytes'], info['md5'])
    core = '\n'.join(rd(os.path.join(GBAJS, 'js', f + '.js')) for f in GBAJS_FILES)
    bios = base64.b64encode(rd(os.path.join(GBAJS, 'resources', 'bios.bin'), 'rb')).decode()
    romb = base64.b64encode(rom).decode()
    api = rd(os.path.join(SRC, 'bsr-api.js'))
    return head + core + '\n\nvar BSR_BIOS_B64="' + bios + '";\nvar BSR_ROM_B64="' + romb + '";\n\n' + api


def build_app():
    parts = ['/* Bullet Storm Raiden web player app (shell + video + UI). (c) 2026 Zachary Peebles. Generated by tools/build_web_player.py */']
    for f in ('bsr-shell.js', 'bsr-video.js', 'bsr-ui.js'):
        parts.append('/* ---- %s ---- */\n' % f + rd(os.path.join(SRC, f)))
    return '\n'.join(parts)


def page(scripts, downloads, rominfo, license_href):
    t = rd(os.path.join(SRC, 'index.template.html'))
    return (t.replace('{{SCRIPTS}}', scripts).replace('{{DOWNLOADS}}', downloads)
             .replace('{{ROMINFO}}', html.escape(rominfo)).replace('{{LICENSE_HREF}}', license_href))


def inline(js):
    return '<script>\n' + js.replace('</script', '<\\/script') + '\n</script>'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('rom', nargs='?', default=os.path.join(ROOT, 'dist', 'BulletStormRaiden_v0.2.gba'))
    ap.add_argument('--skins', action='store_true', help='also rebuild dist/skins (tools/build_skins.py, needs chromium)')
    ap.add_argument('--no-site', action='store_true')
    ap.add_argument('--no-single', action='store_true')
    a = ap.parse_args()
    rom = rd(a.rom, 'rb')
    info = rom_info(rom, a.rom)
    print('ROM %s: title=%s code=%s %d bytes md5=%s header_checksum=%s' % (info['file'], info['title'], info['code'], info['bytes'], info['md5'], 'ok' if info['header_ok'] else 'BAD'))

    if a.skins:
        subprocess.check_call([sys.executable, os.path.join(ROOT, 'tools', 'build_skins.py')])

    bundle = build_bundle(rom, info)
    app = build_app()
    wr(os.path.join(ROOT, 'web', 'bsr-player.js'), bundle)
    wr(os.path.join(ROOT, 'web', 'bsr-app.js'), app)
    print('web/bsr-player.js %d bytes, web/bsr-app.js %d bytes' % (len(bundle), len(app)))

    rominfo = 'ROM %s%s \u00B7 %s bytes \u00B7 md5 %s' % (info['title'], (' ' + info['version']) if info['version'] else '', format(info['bytes'], ','), info['md5'])
    skins = os.path.join(ROOT, 'dist', 'skins')
    if not a.no_site:
        site = os.path.join(ROOT, 'site')
        os.makedirs(site, exist_ok=True)
        wr(os.path.join(site, 'bsr-player.js'), bundle)
        wr(os.path.join(site, 'bsr-app.js'), app)
        romname = 'BulletStormRaiden.gba'
        wr(os.path.join(site, romname), rom)
        shutil.copyfile(os.path.join(GBAJS, 'COPYING'), os.path.join(site, 'gbajs-LICENSE.txt'))
        wr(os.path.join(site, '.nojekyll'), '')
        dl = ['<a href="%s" download>Download the ROM (.gba)</a>' % romname]
        dld = os.path.join(site, 'downloads')
        if os.path.isdir(skins):
            if os.path.isdir(dld):
                shutil.rmtree(dld)
            os.makedirs(dld)
            ds = os.path.join(skins, 'BSR_GreenShell.deltaskin')
            if os.path.exists(ds):
                shutil.copyfile(ds, os.path.join(dld, 'BSR_GreenShell.deltaskin'))
                dl.append('<a href="downloads/BSR_GreenShell.deltaskin" download>Delta skin (.deltaskin)</a>')
            ra = os.path.join(skins, 'retroarch')
            if os.path.isdir(ra):
                zp = shutil.make_archive(os.path.join(dld, 'BSR_GreenShell_RetroArch'), 'zip', ra)
                dl.append('<a href="downloads/%s" download>RetroArch overlay (.zip)</a>' % os.path.basename(zp))
        scripts = '<script src="bsr-player.js"></script>\n<script src="bsr-app.js"></script>'
        wr(os.path.join(site, 'index.html'), page(scripts, '\n    '.join(dl), rominfo, 'gbajs-LICENSE.txt'))
        wr(os.path.join(site, 'README.md'),
           '# Bullet Storm Raiden: web player (static site)\n\nServe this folder as static files (GitHub Pages: Settings > Pages > '
           'deploy from branch, folder `/site` or copy it to `/docs`). Everything runs client-side; no build step.\n\n'
           'Regenerate from a new ROM: `python3 tools/build_web_player.py dist/BulletStormRaiden_vX.Y.gba --skins`\n\n'
           'Emulation: gbajs (c) 2012 Jeffrey Pfau, BSD 2-clause (gbajs-LICENSE.txt).\n')
        print('site/ written (%s)' % ', '.join(sorted(os.listdir(site))))
    if not a.no_single:
        single = page(inline(bundle) + '\n' + inline(app),
                      '<a href="https://github.com/purrpgoddpeebles91/Bullet-Storm-Raiden-GBA" rel="noopener">ROM, Delta skin and RetroArch overlay on GitHub</a>',
                      rominfo, 'https://github.com/endrift/gbajs/blob/master/COPYING')
        out = os.path.join(ROOT, 'dist', 'web', 'BulletStormRaiden_web_single.html')
        wr(out, single)
        print('%s %d bytes' % (os.path.relpath(out, ROOT), len(single)))


if __name__ == '__main__':
    main()
